   -- Table 1: Users (Candidates and Admins)
   CREATE TABLE users (
       user_id SERIAL PRIMARY KEY,
       name VARCHAR(100) NOT NULL,
       email VARCHAR(100) UNIQUE NOT NULL,
       password_hash VARCHAR(255) NOT NULL,
       role VARCHAR(20) DEFAULT 'candidate',
       created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
   );

   -- Table 2: Interview Sessions
   CREATE TABLE interview_sessions (
       session_id SERIAL PRIMARY KEY,
       user_id INT REFERENCES users(user_id) ON DELETE CASCADE,
       job_role VARCHAR(100) NOT NULL,
       experience_level VARCHAR(50),
       status VARCHAR(20) DEFAULT 'pending',
       started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
       completed_at TIMESTAMP
   );

   -- Table 3: Questions (Generated by AI)
   CREATE TABLE questions (
       question_id SERIAL PRIMARY KEY,
       session_id INT REFERENCES interview_sessions(session_id) ON DELETE CASCADE,
       question_text TEXT NOT NULL,
       category VARCHAR(50),
       difficulty VARCHAR(20)
   );

   -- Table 4: Candidate Responses
   CREATE TABLE responses (
       response_id SERIAL PRIMARY KEY,
       question_id INT REFERENCES questions(question_id) ON DELETE CASCADE,
       user_id INT REFERENCES users(user_id) ON DELETE CASCADE,
       answer_text TEXT NOT NULL,
       submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
   );

   -- Table 5: Career Coach Feedback
   CREATE TABLE feedback (
       feedback_id SERIAL PRIMARY KEY,
       session_id INT REFERENCES interview_sessions(session_id) ON DELETE CASCADE,
       user_id INT REFERENCES users(user_id) ON DELETE CASCADE,
       technical_score DECIMAL(5,2),
       behavioral_score DECIMAL(5,2),
       strengths TEXT,
       weaknesses TEXT,
       career_recommendations TEXT,
       generated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
   );